from __future__ import annotations
from agent_tools.configuration import DISCOVERY_KINDS
from agent_tools.runtime import PRIMARY as PRIMARY_AGENTS_DIR, extract_platform_instances, platform_active, settings
from pathlib import Path
# 2026-11-26 "Move analysis workflow classes into Df/Harness single-class modules": https://github.com/dmitry-ai/harness/issues/380
class GlobalCustomizationManager:
	GLOBAL_KINDS = DISCOVERY_KINDS
	HOOK_RUNNER_HEADER = '# Generated by Harness; do not edit.\n# https://github.com/dmitry-ai/harness/issues/103\n'
	UNDECLARED_ANTIGRAVITY_HOME = 'current-undeclared'
	# @used-by :func:`agent_tools.upwork_project.antigravity_global_config_dirs()`
	# @used-by :meth:`GlobalCustomizationManager.check_global()`
	# @used-by :meth:`GlobalCustomizationManager.install_global()`
	# @used-by :meth:`test_df_harness_s11_wave2a_upwork.DfHarnessS11Wave2aUpworkTests.test_z_upwork_global_custom_and_doctor()`
	@classmethod
	def antigravity_global_config_dirs(cls, *, settings_fn=None) -> dict[str, Path]:
		from agent_tools.path_registry import default_platform_paths
		config = (settings if None is settings_fn else settings_fn)()
		if not platform_active('antigravity', config=config):
			r: dict[str, Path] = {}
		else:
			ag_cfg = config.get('platforms', {}).get('antigravity') or {}
			all_insts = extract_platform_instances(ag_cfg, platform='antigravity', include_disabled=True)
			r = {name: Path(inst['system_paths']['config_dir']) for name, inst in all_insts.items() if inst['enabled'] and 'config_dir' in inst['system_paths']}
			current = Path(default_platform_paths('antigravity')['config_dir'])
			declared = [Path(inst['system_paths']['config_dir']).resolve() for inst in all_insts.values() if 'config_dir' in inst['system_paths']]
			if all((current.resolve() != path for path in declared)):
				r[cls.UNDECLARED_ANTIGRAVITY_HOME] = current
		return r
	# @used-by :func:`agent_tools.upwork_project.canonical_global_hooks()`
	# @used-by :meth:`test_df_harness_s11_wave2a_upwork.DfHarnessS11Wave2aUpworkTests.test_upwork_project_management_classes()`
