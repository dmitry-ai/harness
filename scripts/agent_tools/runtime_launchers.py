_RUNNER_COMMON = (
	'from datetime import datetime, timezone\n'
	'import io\n'
	'import json\n'
	'import os\n'
	'from pathlib import Path\n'
	'import runpy\n'
	'import sys\n'
	'def _log_fallback(store: Path, script_name: str, cur_sha: str, prev_sha: str, exc: BaseException) -> None:\n'
	'\tts = datetime.now(timezone.utc).isoformat()\n'
	'\tline = f"{ts} fallback script={script_name} current={cur_sha} previous={prev_sha} error={type(exc).__name__}: {exc}\\n"\n'
	'\tsys.stderr.write(line)\n'
	'\ttry:\n'
	'\t\tstore.mkdir(parents=True, exist_ok=True)\n'
	"\t\twith (store / 'fallback.log').open('a', encoding='utf-8') as fh:\n"
	'\t\t\tfh.write(line)\n'
	'\texcept OSError:\n'
	'\t\tpass\n'
	'def _purge_loaded(before_keys: set[str], script_stem: str) -> None:\n'
	'\tfor mod_name in list(sys.modules):\n'
	"\t\tif mod_name not in before_keys or 'agent_tools' == mod_name or mod_name.startswith('agent_tools.') or mod_name == script_stem:\n"
	'\t\t\tsys.modules.pop(mod_name, None)\n'
	'def _exec_release_script(release_dir: Path, script_name: str, extra_argv: list[str], raw_stdin: str, *, capture_stdout: bool) -> tuple[str, int]:\n'
	"\tscript_path = (release_dir / 'scripts' / script_name).resolve()\n"
	'\tif not script_path.is_file():\n'
	"\t\traise FileNotFoundError(f'Missing snapshot script: {script_path}')\n"
	'\tscripts_dir = str(script_path.parent)\n'
	'\torig_path, orig_argv, orig_in, orig_out = (list(sys.path), list(sys.argv), sys.stdin, sys.stdout)\n'
	'\tbefore_keys = set(sys.modules)\n'
	'\t_purge_loaded(before_keys, script_path.stem)\n'
	'\tbuf = io.StringIO() if capture_stdout else None\n'
	'\tsys.path = [scripts_dir, *[p for p in orig_path if p != scripts_dir]]\n'
	'\tsys.argv = [str(script_path), *extra_argv]\n'
	'\tsys.stdin = io.StringIO(raw_stdin)\n'
	'\tif None is not buf:\n'
	'\t\tsys.stdout = buf\n'
	'\trc = 0\n'
	'\ttry:\n'
	"\t\trunpy.run_path(str(script_path), run_name='__main__')\n"
	'\texcept SystemExit as se:\n'
	'\t\trc = 0 if None is se.code else (se.code if isinstance(se.code, int) else 1)\n'
	'\texcept BaseException:\n'
	'\t\t_purge_loaded(before_keys, script_path.stem)\n'
	'\t\traise\n'
	'\tfinally:\n'
	'\t\tsys.path, sys.argv, sys.stdin, sys.stdout = (orig_path, orig_argv, orig_in, orig_out)\n'
	"\treturn (buf.getvalue() if None is not buf else '', rc)\n"
	'def _run_from_snapshot(store: Path, script_name: str, extra_argv: list[str], raw_stdin: str, *, capture_stdout: bool) -> tuple[bool, int]:\n'
	"\tptr_file = store / 'current.json'\n"
	"\tif '1' == os.environ.get('HARNESS_DEV_LIVE_HOOKS') or (not ptr_file.is_file()):\n"
	'\t\treturn (False, 0)\n'
	'\ttry:\n'
	"\t\tptr = json.loads(ptr_file.read_text(encoding='utf-8-sig'))\n"
	'\texcept (OSError, ValueError):\n'
	'\t\treturn (False, 0)\n'
	"\tcur_sha = str(ptr.get('current') or '').strip() if isinstance(ptr, dict) else ''\n"
	"\tprev_sha = str(ptr.get('previous') or '').strip() if isinstance(ptr, dict) else ''\n"
	'\tif not cur_sha:\n'
	'\t\treturn (False, 0)\n'
	'\ttry:\n'
	"\t\tout, rc = _exec_release_script(store / 'releases' / cur_sha, script_name, extra_argv, raw_stdin, capture_stdout=capture_stdout)\n"
	'\texcept Exception as exc:\n'
	'\t\tif prev_sha and prev_sha != cur_sha:\n'
	'\t\t\t_log_fallback(store, script_name, cur_sha, prev_sha, exc)\n'
	"\t\t\tout, rc = _exec_release_script(store / 'releases' / prev_sha, script_name, extra_argv, raw_stdin, capture_stdout=capture_stdout)\n"
	'\t\telse:\n'
	'\t\t\traise\n'
	'\tif out:\n'
	'\t\tsys.stdout.write(out)\n'
	'\treturn (True, rc)\n'
)
