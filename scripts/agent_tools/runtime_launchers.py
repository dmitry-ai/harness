	'\tout = [cand]\n'
	"\tif cand.parts[-4:] in (('\\u2c0f', '\\u227b', '\\u2655', '\\u26ef'), ('Artifacts', '\\u227b', 'Deliverables', '\\u26ef')):\n"
	'\t\tbase = cand.parents[3]\n'
	'\t\tout.extend((base / rel for rel in V2_RELS))\n'
	"\telif 'code' == cand.name:\n"
	'\t\tbase = cand.parent\n'
